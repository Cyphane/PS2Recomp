#!/bin/sh
# Regenerates gs_vulkan_shaders.inc from the GLSL sources (needs glslangValidator).
set -e
cd "$(dirname "$0")"
out=../gs_vulkan_shaders.inc
echo "// Generated by vk_shaders/gen_shaders.sh - do not edit." > $out
for s in gs_draw.vert gs_draw.frag; do
  glslangValidator -V --target-env vulkan1.2 -o /tmp/$s.spv $s >/dev/null
  name=$(echo $s | tr '.' '_')
  python3 - /tmp/$s.spv $name >> $out <<'PY'
import sys,struct
b=open(sys.argv[1],'rb').read(); w=struct.unpack('<%dI'%(len(b)//4),b)
print('static const uint32_t k_%s[] = {'%sys.argv[2])
for i in range(0,len(w),8): print('    '+', '.join('0x%08xu'%x for x in w[i:i+8])+',')
print('};')
PY
done
